/**
 * Offline generator for the league board pool (Modes B and C).
 *
 *   npx vite-node scripts/gen-board-pool.ts
 *
 * For each N in 1..10, collects POOL_SIZE distinct 12-card boards with exactly N
 * sets by plain rejection sampling: shuffle, take 12, keep if countSets === N.
 * No hill-climbing or construction — those leave recognisable structure, and the
 * whole point is that a pool board is indistinguishable from a lucky deal.
 *
 * Randomness comes from crypto.getRandomValues, not mulberry32. The pool is
 * committed data, so it never has to be reproduced from a seed, and this keeps
 * it clear of mulberry32's single 2^32 cycle (see CLAUDE.md).
 *
 * Each board is stored as its 12 card ids sorted ascending: the client reshuffles
 * anyway, and sorted ids make duplicate detection a string compare. Every board
 * is re-verified with the brute-force enumeration before it is written.
 *
 * Output: supabase/board-pool/pool-NN.sql, one multi-row insert per N.
 */

import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { cardId, fullDeck, type Card } from '../src/game/cards'
import { countSets, enumerateSetsBrute } from '../src/game/set'

const POOL_SIZE = 2000
const MIN_N = 1
const MAX_N = 10
const BOARD_SIZE = 12

/** Buffered crypto randomness — one getRandomValues call per 16K draws. */
const buf = new Uint32Array(16384)
let pos = buf.length
function u32(): number {
  if (pos === buf.length) {
    crypto.getRandomValues(buf)
    pos = 0
  }
  return buf[pos++]!
}

/** Unbiased uniform integer in [0, m), by rejecting the short top bucket. */
function below(m: number): number {
  const limit = 2 ** 32 - (2 ** 32 % m)
  for (;;) {
    const x = u32()
    if (x < limit) return x % m
  }
}

/**
 * Deal 12 cards: the first 12 steps of a Fisher–Yates shuffle over the full
 * deck, which is exactly a uniform 12-card draw without replacement. `deck` is
 * permuted in place and reused; only its prefix is read.
 */
function deal(deck: Card[]): Card[] {
  for (let i = 0; i < BOARD_SIZE; i++) {
    const j = i + below(deck.length - i)
    const tmp = deck[i]!
    deck[i] = deck[j]!
    deck[j] = tmp
  }
  return deck.slice(0, BOARD_SIZE)
}

function main(): void {
  const outDir = fileURLToPath(new URL('../supabase/board-pool/', import.meta.url))
  mkdirSync(outDir, { recursive: true })

  const deck = fullDeck()
  const pools = new Map<number, Map<string, number[]>>()
  for (let n = MIN_N; n <= MAX_N; n++) pools.set(n, new Map())

  // One shared stream of deals feeds every N at once, so the rare high counts
  // are collected while the common ones fill up. Each N reports the
  // total deals made by the time its pool filled.
  const start = performance.now()
  let total = 0
  let open = MAX_N - MIN_N + 1
  while (open > 0) {
    const cards = deal(deck)
    total++
    if (total % 10_000_000 === 0) {
      const left = [...pools].filter(([, p]) => p.size < POOL_SIZE).map(([n, p]) => `N=${n}: ${p.size}`)
      console.log(`  ...${total / 1e6}M deals, ${((performance.now() - start) / 1000).toFixed(0)}s, filling ${left.join(', ')}`)
    }
    const n = countSets(cards)
    const pool = pools.get(n)
    if (pool === undefined || pool.size >= POOL_SIZE) continue
    const ids = cards.map(cardId).sort((a, b) => a - b)
    const key = ids.join(',')
    if (pool.has(key)) continue
    if (enumerateSetsBrute(cards).length !== n) throw new Error(`count mismatch on ${key}`)
    pool.set(key, ids)
    if (pool.size === POOL_SIZE) {
      open--
      console.log(
        `N=${String(n).padStart(2)}  full after ${total.toLocaleString('en')} deals (~${Math.round(total / POOL_SIZE).toLocaleString('en')} per board), ${((performance.now() - start) / 1000).toFixed(1)}s`,
      )
    }
  }
  const elapsed = (performance.now() - start) / 1000
  console.log(`\n${total.toLocaleString('en')} deals in ${elapsed.toFixed(1)}s (${((elapsed * 1e6) / total).toFixed(2)} µs/deal)`)

  for (let n = MIN_N; n <= MAX_N; n++) {
    const rows = [...pools.get(n)!.values()].sort((a, b) => a.join(',').localeCompare(b.join(',')))
    const file = `pool-${String(n).padStart(2, '0')}.sql`
    const values = rows.map((ids) => `(${n}, '{${ids.join(',')}}')`).join(',\n')
    const sql =
      `-- Board pool, N = ${n}: ${rows.length} distinct 12-card boards with exactly ${n} sets.\n` +
      `-- Generated by scripts/gen-board-pool.ts (crypto RNG, plain rejection sampling).\n` +
      `-- Card ids are sorted ascending; the client relabels and reshuffles each one.\n` +
      `-- Re-runnable: rows already present are skipped.\n` +
      `insert into board_pool (n, cards) values\n${values}\non conflict (cards) do nothing;\n`
    writeFileSync(outDir + file, sql)
  }
  console.log(`\nwrote ${MAX_N - MIN_N + 1} files to supabase/board-pool/`)
}

main()
